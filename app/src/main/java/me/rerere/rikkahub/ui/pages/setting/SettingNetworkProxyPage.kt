import org.koin.androidx.compose.koinViewModel

@Composable
fun SettingNetworkProxyPage(vm: SettingVM = koinViewModel()) {
    val settings by vm.settings.collectAsStateWithLifecycle()

    val scrollBehavior = TopAppBarDefaults.exitUntilCollapsedScrollBehavior()

    Scaffold(
        topBar = {
            LargeFlexibleTopAppBar(
                title = {
                    Text(stringResource(R.string.setting_network_proxy_title))
                },
                navigationIcon = {
                    BackButton()
                },
                scrollBehavior = scrollBehavior,
                colors = CustomColors.topBarColors
            )
        },
        modifier = Modifier.nestedScroll(scrollBehavior.nestedScrollConnection),
        containerColor = CustomColors.topBarColors.containerColor
    ) { contentPadding ->
        LazyColumn(
            modifier = Modifier.fillMaxSize(),
            contentPadding = contentPadding + PaddingValues(8.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            item {
                CardGroup(
                    modifier = Modifier.padding(horizontal = 8.dp),
                    title = { Text(stringResource(R.string.setting_network_proxy)) },
                ) {
                    item(
                        headlineContent = { Text(stringResource(R.string.setting_network_proxy_title)) },
                        supportingContent = { Text(stringResource(R.string.setting_network_proxy_subtitle)) },
                    )
                    item {
                        ProxyConfigEditor(
                            proxy = settings.globalProxy,
                            allowSocks4 = false,
                            onEdit = { proxy ->
                                vm.updateSettings(settings.copy(globalProxy = proxy))
                            },
                        )
                    }
                }
            }
        }
    }
}
